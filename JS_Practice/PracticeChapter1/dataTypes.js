console.log("Difference between let and const variables ");

let url1 = "https://www.example.com";
console.log(url1);
console.log(typeof url1);
let timeout1 = 30000;
console.log(timeout1);
console.log(typeof timeout1);      

console.log("Boolean data type in javascript");
const isLoggedIn = true;
console.log(isLoggedIn);
console.log(typeof isLoggedIn); 

console.log("Null data type in javascript");
const token = null;
console.log(token);
console.log(typeof token);

