//Arithmetic Operators
console.log("Arithmetic Operators:");
let a = 10;
let b = 5;
console.log("Addition: ", a + b); // Addition operator +
console.log("Subtraction: ", a - b);  // Subtraction operator -
console.log("Multiplication: ", a * b); // Multiplication operator *
console.log("Division:" , a / b); // Division operator /
console.log("Modulus: ", a % b); // Modulus operator %

// Comparison Operators

console.log("Comparison Operators:");
let number1 = 11;
let number2 = 18;
console.log(11 > 18); // Greater than operator >
console.log(11 < 18); // Less than operator <
console.log(11 >= 18); // Greater than or equal to operator >=
console.log(11 <= 18); // Less than or equal to operator <=
console.log(11 === 18); // Strict equality operator ===
console.log(11 !== 18); // Strict inequality operator !==

// Equality Operators
console.log("Equality Operators:");
console.log(10 == 10); // Loose equality operator ==
console.log(10 === "10"); // Strict equality operator ===
console.log(10 === '10'); // Loose inequality operator !=
console.log("10" === '10'); // Strict inequality operator !==
