let age = "Siva" // String literal
console.log(age); // Siva
let isStudent = true; // Boolean literal
console.log(isStudent); // true
let pi = 3.14; // Number literal    
console.log(pi); // 3.14    
let nullValue = null; // Null literal
console.log(nullValue); // null
let email; // Undefined literal
console.log(email); // undefined
let name = 'Alice'; // String literal
console.log(name);

console.log("Type of age: " + typeof age); // string
console.log("Type of isStudent: " + typeof isStudent); // boolean
console.log("Type of pi: " + typeof pi); // number
console.log("Type of nullValue: " + typeof nullValue); // object
console.log("Type of email: " + typeof email); // undefined, if variable is not assigned any value, it is considered undefined  
 

